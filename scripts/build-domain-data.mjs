/**
 * Build the domain reference data the engine ships with.
 *
 *   npm run domain-data   (network; commit the outputs)
 *
 * 1. Public Suffix List (publicsuffix.org, MPL-2.0)  -> src/engine/domain/psl-data.ts
 *    ICANN and private sections, unicode rules converted to punycode.
 * 2. Majestic Million (CC BY 3.0, majestic.com)      -> public/data/popular-domains.txt
 *    Top POPULAR_COUNT registrable domains. Used only as *negative* evidence for
 *    domain-name impersonation ("netflix.net is Netflix's, not a lookalike").
 *    Any domain also present in the shipped phishing feed is dropped.
 *    Test corpora for false-positive measurement go to tests/fixtures/.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import punycode from "punycode/punycode.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PSL_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const MAJESTIC_URL = "https://downloads.majestic.com/majestic_million.csv";
const POPULAR_COUNT = 50_000;

async function text(url) {
  const response = await fetch(url, { headers: { "User-Agent": "fundament-data-builder" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

function parsePsl(raw) {
  const rules = [];
  for (const line of raw.split(/\r?\n/)) {
    const rule = line.trim().split(/\s/)[0] ?? "";
    if (!rule || rule.startsWith("//")) continue;
    const exception = rule.startsWith("!");
    const body = exception ? rule.slice(1) : rule;
    const ascii = body
      .split(".")
      .map((label) => (label === "*" ? "*" : punycode.toASCII(label.toLowerCase())))
      .join(".");
    rules.push(exception ? `!${ascii}` : ascii);
  }
  return [...new Set(rules)].sort();
}

/** Same algorithm as src/engine/domain/psl.ts (kept small and dependency-free). */
function makeRegistrable(rules) {
  const exact = new Set();
  const wildcard = new Set();
  const exceptions = new Set();
  for (const rule of rules) {
    if (rule.startsWith("!")) exceptions.add(rule.slice(1));
    else if (rule.startsWith("*.")) wildcard.add(rule.slice(2));
    else exact.add(rule);
  }
  return (host) => {
    const labels = host.split(".");
    let suffixLen = 1;
    for (let i = 0; i < labels.length; i++) {
      const candidate = labels.slice(i).join(".");
      const parent = labels.slice(i + 1).join(".");
      if (exceptions.has(candidate)) {
        suffixLen = labels.length - i - 1;
        break;
      }
      if (exact.has(candidate) || (parent && wildcard.has(parent))) {
        suffixLen = labels.length - i;
        break;
      }
    }
    if (labels.length <= suffixLen) return null;
    return labels.slice(labels.length - suffixLen - 1).join(".");
  };
}

async function main() {
  const rules = parsePsl(await text(PSL_URL));
  if (rules.length < 5000) throw new Error(`PSL too small (${rules.length})`);
  const header = [
    "// Generated by scripts/build-domain-data.mjs from https://publicsuffix.org/list/public_suffix_list.dat",
    "// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.",
    "// If a copy of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.",
    `// Rules: ${rules.length}. Generated: ${new Date().toISOString()}`,
  ].join("\n");
  writeFileSync(resolve(root, "src/engine/domain/psl-data.ts"), `${header}\nexport const PSL_RULES = ${JSON.stringify(rules.join("\n"))};\n`);

  const registrable = makeRegistrable(rules);

  const csv = await text(MAJESTIC_URL);
  const ranked = [];
  const seen = new Set();
  for (const line of csv.split(/\r?\n/).slice(1)) {
    const domain = (line.split(",")[2] ?? "").trim().toLowerCase();
    if (!domain || !/^[a-z0-9.-]+$/.test(domain)) continue;
    const reg = registrable(domain);
    if (!reg || seen.has(reg)) continue;
    seen.add(reg);
    ranked.push(reg);
  }
  // Popularity is independent of the feed: the feed builder drops popular hosts, not the other way round.
  const popular = ranked.slice(0, POPULAR_COUNT);
  mkdirSync(resolve(root, "public/data"), { recursive: true });
  writeFileSync(
    resolve(root, "public/data/popular-domains.txt"),
    `# Majestic Million (CC BY 3.0, https://majestic.com/reports/majestic-million), top ${POPULAR_COUNT} registrable domains, ${new Date().toISOString().slice(0, 10)}\n${popular.join("\n")}\n`,
  );

  mkdirSync(resolve(root, "tests/fixtures"), { recursive: true });
  const fixtureHeader = (what) =>
    `# ${what} — Majestic Million (CC BY 3.0, https://majestic.com/reports/majestic-million), ${new Date().toISOString().slice(0, 10)}. Regenerate with npm run domain-data.\n`;
  writeFileSync(resolve(root, "tests/fixtures/popular-top10k.txt"), fixtureHeader("Ranks 1-10,000") + ranked.slice(0, 10_000).join("\n") + "\n");
  writeFileSync(
    resolve(root, "tests/fixtures/longtail-sample.txt"),
    fixtureHeader("Ranks 100,001-110,000 (outside the shipped popularity set)") + ranked.slice(100_000, 110_000).join("\n") + "\n",
  );
  process.stdout.write(`psl rules ${rules.length}; popular ${popular.length}; ranked ${ranked.length}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
